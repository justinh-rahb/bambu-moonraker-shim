def png(width=2, height=2):
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 2, 0, 0, 0)) + chunk(b'IDAT', zlib.compress((b'\0' + b'\xff\0\0' * width) * height)) + chunk(b'IEND', b'')


GCODE = b'''; generated by OrcaSlicer 2.4.2 on today
; total estimated time: 24m 11s
; total layer number: 192
; max_z_height: 48.00
; layer_height = 0.25
; initial_layer_print_height = 0.25
; nozzle_diameter = 0.4
; nozzle_temperature_initial_layer = 220
; bed_temperature_initial_layer_single = 55
; filament_type = PLA;ABS
; filament_settings_id = "PLA Profile";"Unused ABS"
G1 Z90 ; travel lift must not become object height
; filament used [mm] = 3589.84, 0
; filament used [g] = 10.88, 0
'''


def archive(plates=None, extra=None):
    data = io.BytesIO()
    with zipfile.ZipFile(data, 'w', compression=zipfile.ZIP_DEFLATED) as z:
        for plate, text in (plates or {1: GCODE}).items():
            z.writestr(f'Metadata/plate_{plate}.gcode', text)
            z.writestr(f'Metadata/plate_{plate}.png', png(plate + 2, plate + 2))
            z.writestr(f'Metadata/plate_{plate}_small.png', png())
        for name, value in (extra or {}).items():
            z.writestr(name, value)
    return data.getvalue()


class MetadataParserTests(unittest.TestCase):
    def test_3mf_uses_sliced_values_and_matching_previews(self):
        metadata, images = parse_file(archive(), 'model.gcode.3mf')
        self.assertEqual(metadata['estimated_time'], 1451)
        self.assertEqual(metadata['layer_count'], 192)
        self.assertEqual(metadata['object_height'], 48)
        self.assertEqual(metadata['filament_total'], 3589.84)
        self.assertEqual(metadata['filament_weight_total'], 10.88)
        self.assertEqual(metadata['filament_type'], 'PLA')
        self.assertEqual(metadata['filament_name'], 'PLA Profile')
        self.assertEqual(metadata['slicer'], 'OrcaSlicer')
        self.assertEqual(metadata['first_layer_extr_temp'], 220)
        self.assertEqual([v['width'] for v in thumbnail_records(images)[0]], [2, 3, 64])

    def test_plate_selection_does_not_mix_metadata_or_images(self):
        data = archive({1: GCODE, 2: b'; generated by BambuStudio 2.0\n; total estimated time: 1h 2m\n'})
        result, images = parse_file(data, 'multi.3mf', 2)
        self.assertEqual(result['estimated_time'], 3720)
        self.assertEqual(result['plate_count'], 2)
        self.assertNotIn('filament_total', result)
        self.assertIn(4, [v['width'] for v in thumbnail_records(images)[0]])
        with self.assertRaises(MetadataError):
            parse_file(data, 'multi.3mf', 3)

    def test_slice_xml_is_plate_specific_and_converts_metres(self):
        xml = '<config><plate><metadata key="index" value="1"/><metadata key="prediction" value="60"/><filament type="ABS" used_m="1.23" used_g="4.5" color="#123456"/></plate><plate><metadata key="index" value="2"/><metadata key="prediction" value="99"/></plate></config>'
        result, _ = parse_file(archive({1: b'G28'}, {'Metadata/slice_info.config': xml}), 'slice.3mf')
        self.assertEqual(result['estimated_time'], 60)
        self.assertEqual(result['filament_total'], 1230)
        self.assertEqual(result['filament_weight_total'], 4.5)
        self.assertEqual(result['filament_colors'], ['#123456'])

    def test_plain_gcode_embedded_png_and_prusa_time(self):
        data = b'; generated by PrusaSlicer 2.8.0\n; estimated printing time (normal mode) = 1d 2h 3m 4s\n; thumbnail begin 2x2 123\n; ' + base64.b64encode(png()) + b'\n; thumbnail end\n'
        result, images = parse_file(data, 'plain.gcode')
        self.assertEqual(result['estimated_time'], 93784)
        self.assertEqual(images, [png()])

    def test_cura_units_and_missing_fields(self):
        result, _ = parse_file(b';Generated with Cura_SteamEngine 5.8\n;TIME:123\n;Filament used: 1.234m\n;Layer height: 0.2\n;MAXZ:4.2\n', 'cura.gcode')
        self.assertEqual(result['filament_total'], 1234)
        self.assertEqual(result['object_height'], 4.2)
        self.assertEqual(result['slicer'], 'Cura')
        result, images = parse_file(b'G28\n', 'unknown.gcode')
        self.assertEqual(result, {})
        self.assertEqual(images, [])

    def test_corrupt_unsliced_and_oversized_archives_are_explicit_errors(self):
        for data in (b'not a ZIP', archive(extra={'Metadata/slice_info.config': '<broken'})):
            with self.assertRaises(MetadataError) as caught:
                parse_file(data, 'broken.3mf')
            self.assertEqual(caught.exception.code, 422)
        with patch('bambu_moonraker_shim.file_metadata.MAX_MEMBER_SIZE', 10):
            with self.assertRaises(MetadataError) as caught:
                parse_file(archive(), 'huge.3mf')
            self.assertEqual(caught.exception.code, 413)
        with self.assertRaises(MetadataError):
            parse_file(archive(), 'plain.gcode', 2)

    def test_external_entities_and_invalid_embedded_images_are_rejected(self):
        xml = '<!DOCTYPE x [<!ENTITY y "bad">]><config/>'
        with self.assertRaises(MetadataError):
            parse_file(archive(extra={'Metadata/slice_info.config': xml}), 'bad.3mf')
        result, images = parse_file(b'; thumbnail begin 2x2 1\n; !!!\n; thumbnail end', 'bad.gcode')
        self.assertEqual(images, [])

    def test_jpeg_preview_is_decoded_and_gets_a_mainsail_list_icon(self):
        from PIL import Image
        stream = io.BytesIO()
        Image.new('RGB', (128, 128), 'blue').save(stream, format='JPEG')
        data = b'; thumbnail_JPG begin 128x128 1\n; ' + base64.b64encode(stream.getvalue()) + b'\n; thumbnail_JPG end\n'
        _, images = parse_file(data, 'jpeg.gcode')
        records, blobs = thumbnail_records(images)
        self.assertEqual([r['width'] for r in records], [64, 128])
        self.assertTrue(any(key.endswith('.jpg') for key in blobs))


    def test_native_bambu_header_preserves_precise_length_over_rounded_xml(self):
        gcode = b'; HEADER_BLOCK_START\n; BambuStudio 02.03.01.51\n; total filament length [mm] : 3088.43\n; total filament weight [g] : 9.36\n; filament_settings_id = "Used PLA";"Unused ABS"\n'
        xml = '<config><plate><metadata key="index" value="1"/><filament type="PLA" used_m="3.09" used_g="9.36"/></plate></config>'
        result, _ = parse_file(archive({1: gcode}, {'Metadata/slice_info.config': xml}), 'cube.3mf')
        self.assertEqual(result['slicer'], 'BambuStudio')
        self.assertEqual(result['slicer_version'], '02.03.01.51')
        self.assertEqual(result['filament_total'], 3088.43)
        self.assertEqual(result['filament_weight_total'], 9.36)
        self.assertNotIn('filament_name', result)

    def test_default_selection_handles_numbered_single_plate_exports(self):
        data = archive({4: GCODE})
        result, images = parse_file(data, 'plate_4.gcode.3mf')
        self.assertEqual(result['plate'], 4)
        self.assertEqual(result['plate_count'], 1)
        self.assertTrue(images)
        with self.assertRaises(MetadataError):
            parse_file(data, 'plate_4.gcode.3mf', 1)


class MetadataServiceTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.db = SQLiteManager(str(self.root / 'shim.db'))
        self.service = MetadataService()
        self.ftp = Mock()
        for key, value in (('BAMBU_SERIAL', ''), ('GCODES_DIR', str(self.root))):
            p = patch.object(api.Config, key, value)
            p.start()
            self.addCleanup(p.stop)

    def create(self, name='file.gcode.3mf', data=None):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(archive() if data is None else data)
        return path

    async def get(self, name='file.gcode.3mf', plate=1, force=False):
        return await self.service.get(name, plate, force, self.ftp, self.db)

    async def test_exact_source_size_mtime_and_restart_durability(self):
        path = self.create()
        result = await self.get()
        self.assertEqual(result['size'], path.stat().st_size)
        self.assertEqual(result['modified'], path.stat().st_mtime)
        self.assertEqual(result['filament_total'], 3589.84)
        with patch('bambu_moonraker_shim.metadata_service.parse_file', side_effect=AssertionError('cached')):
            self.service = MetadataService()
            self.db = SQLiteManager(str(self.root / 'shim.db'))
            self.assertEqual(await self.get(), result)
        key = result['thumbnails'][0]['relative_path'].split('/')[-1]
        self.assertEqual(self.db.get_thumbnail(key), png())
        self.ftp.download_file.assert_not_called()

    async def test_replacement_and_explicit_rescan_refresh_cache(self):
        path = self.create()
        old = await self.get()
        path.write_bytes(archive({1: GCODE.replace(b'24m 11s', b'10m 11s')}))
        new = await self.get()
        self.assertEqual(new['estimated_time'], 611)
        self.assertNotEqual(old['uuid'], new['uuid'])
        with patch('bambu_moonraker_shim.metadata_service.parse_file', wraps=parse_file) as parse:
            await self.get(force=True)
        parse.assert_called_once()

    async def test_concurrent_requests_parse_once(self):
        self.create()
        with patch('bambu_moonraker_shim.metadata_service.parse_file', wraps=parse_file) as parse:
            results = await asyncio.gather(*(self.get() for _ in range(8)))
        self.assertEqual(results, [results[0]] * 8)
        parse.assert_called_once()

    async def test_missing_paths_and_symlink_escape_do_not_download(self):
        for name, plate in (('missing.gcode', 1), ('../escape.gcode', 1), ('/abs.gcode', 1), ('foo\nRETR.gcode', 1), ('file.3mf', 0), ('file.3mf', True)):
            with self.subTest(name=name, plate=plate), self.assertRaises(MetadataError):
                await self.get(name, plate)
        os.symlink('/etc/hosts', self.root / 'escape.gcode')
        with self.assertRaises(MetadataError):
            await self.get('escape.gcode')
        self.ftp.download_file.assert_not_called()

    async def test_unknown_metadata_does_not_fabricate_fields(self):
        self.create('unknown.gcode', b'G28')
        result = await self.get('unknown.gcode')
        for key in ('slicer', 'estimated_time', 'filament_total', 'layer_height', 'object_height'):
            self.assertNotIn(key, result)
        self.assertEqual(result['size'], 3)
        self.assertEqual(result['thumbnails'], [])

    async def test_remote_metadata_downloads_and_caches_without_mutation(self):
        data = archive()
        self.ftp.list_files.return_value = [dict(name='remote.3mf', size=len(data), modified=100, is_dir=False)]
        self.ftp.download_file.return_value = data
        with patch.object(api.Config, 'BAMBU_SERIAL', 'TEST'):
            first = await self.get('remote.3mf')
            self.assertEqual(await self.get('remote.3mf'), first)
        self.ftp.download_file.assert_called_once()
        self.ftp.delete_file.assert_not_called()
        self.ftp.upload_file.assert_not_called()

    async def test_http_rpc_and_thumbnail_routes_agree(self):
        self.create('folder/spaced file.3mf')
        with patch.object(api, 'get_sqlite_manager', return_value=self.db), patch.object(api, 'metadata_service', self.service):
            http = await api.file_metadata('folder/spaced file.3mf')
            rpc = await api.handle_jsonrpc({'jsonrpc': '2.0', 'id': 1, 'method': 'server.files.metadata', 'params': {'filename': 'folder/spaced file.3mf'}}, 1)
            self.assertEqual(http['result'], rpc['result'])
            thumbnail = http['result']['thumbnails'][0]
            response = await api.file_download('gcodes', 'folder/' + thumbnail['relative_path'])
            self.assertEqual(response.body, png())
            self.assertEqual(response.media_type, 'image/png')
            details = await api.file_thumbnails('folder/spaced file.3mf')
            self.assertEqual(details['result'][0]['thumbnail_path'], 'folder/' + thumbnail['relative_path'])
            error = await api.file_metadata('missing.gcode')
            self.assertEqual(error.status_code, 404)

    async def test_invalidation_removes_metadata_and_orphan_thumbnails(self):
        self.create()
        result = await self.get()
        self.db.invalidate_parsed_metadata('file.gcode.3mf')
        key = result['thumbnails'][0]['relative_path'].split('/')[-1]
        self.assertIsNone(self.db.get_thumbnail(key))
        with patch('bambu_moonraker_shim.metadata_service.parse_file', wraps=parse_file) as parse:
            await self.get()
        parse.assert_called_once()

    async def test_changed_during_download_is_not_cached(self):
        data = archive()
        self.ftp.list_files.side_effect = [
            [dict(name='changing.3mf', size=len(data), modified=100, is_dir=False)],
            [dict(name='changing.3mf', size=len(data), modified=101, is_dir=False)],
        ]
        self.ftp.download_file.return_value = data
        with patch.object(api.Config, 'BAMBU_SERIAL', 'TEST'), self.assertRaises(MetadataError) as caught:
            await self.get('changing.3mf')
        self.assertEqual(caught.exception.code, 409)
        self.assertIsNone(self.db.get_parsed_metadata('changing.3mf', 1, 1, len(data), 100))

    async def test_plate_caches_do_not_collide(self):
        self.create(data=archive({1: GCODE, 2: b';TIME:20\n'}))
        self.assertEqual((await self.get())['estimated_time'], 1451)
        self.assertEqual((await self.get(plate=2))['estimated_time'], 20)
        self.assertEqual((await self.get())['estimated_time'], 1451)

    async def test_transport_failure_does_not_return_live_fallback(self):
        self.ftp.list_files.return_value = [dict(name='failed.gcode', size=20, modified=100, is_dir=False)]
        self.ftp.download_file.side_effect = OSError('transfer failed')
        with patch.object(api.Config, 'BAMBU_SERIAL', 'TEST'), self.assertRaises(MetadataError) as caught:
            await self.get('failed.gcode')
        self.assertEqual(caught.exception.code, 502)

    async def test_extended_directory_contains_metadata_without_overwriting_names(self):
        self.create()
        with patch.object(api, 'get_sqlite_manager', return_value=self.db), patch.object(api, 'metadata_service', self.service):
            result = await api.handle_jsonrpc({'jsonrpc': '2.0', 'id': 1, 'method': 'server.files.get_directory', 'params': {'path': 'gcodes', 'extended': True}}, 1)
        item = next(f for f in result['result']['files'] if f['filename'] == 'file.gcode.3mf')
        self.assertEqual(item['estimated_time'], 1451)
        self.assertTrue(item['thumbnails'])

    async def test_unknown_remote_timestamp_is_rechecked_after_five_minutes(self):
        data = archive()
        self.ftp.list_files.return_value = [dict(name='unknown.3mf', size=len(data), modified=0, is_dir=False)]
        self.ftp.download_file.return_value = data
        with patch.object(api.Config, 'BAMBU_SERIAL', 'TEST'):
            with patch('bambu_moonraker_shim.metadata_service.time.time', return_value=1000):
                await self.get('unknown.3mf')
            with patch('bambu_moonraker_shim.metadata_service.time.time', return_value=1301):
                await self.get('unknown.3mf')
        self.assertEqual(self.ftp.download_file.call_count, 2)

    async def test_api_auto_selects_the_available_plate(self):
        self.create(data=archive({4: GCODE}))
        with patch.object(api, 'get_sqlite_manager', return_value=self.db), patch.object(api, 'metadata_service', self.service):
            result = (await api.file_metadata('file.gcode.3mf'))['result']
            self.assertEqual(result['plate'], 4)
            self.assertEqual(result['estimated_time'], 1451)
            self.assertEqual((await api.file_metadata('file.gcode.3mf', plate=1)).status_code, 422)
